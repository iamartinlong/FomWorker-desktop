const DAY_MS = 864e5;
/** 存储壳：域之上的一层薄 API（面板/工具都只用它）。 */
var ItemStore = class {
	domain;
	/** 单域条数上限（可注入：单测用小值，生产默认 5000）。 */
	maxItems;
	constructor(domain, options = {}) {
		this.domain = domain;
		this.maxItems = options.maxItems ?? 5e3;
	}
	/** 全部事项（排序见 `sortItems`）。 */
	list() {
		const table = this.domain.table("items");
		const rows = [];
		for (const key of table.keys()) {
			const row = table.get(key);
			if (row !== void 0) rows.push(row);
		}
		return sortItems(rows);
	}
	/** 单条。 */
	get(id) {
		return this.domain.table("items").get(id);
	}
	/**
	* 新增一条（超上限拒）。
	* @param text 正文
	* @param now 当前时刻（UTC 毫秒）
	* @param options 来源 / 到期 / 会话
	* @param idOf id 工厂（缺省随机 UUID）
	*/
	async add(text, now, options = {}, idOf = () => crypto.randomUUID()) {
		if (this.domain.table("items").size >= this.maxItems) throw new Error(`事项已达上限（${this.maxItems} 条），先清理一些已完成事项`);
		const item = newItem({
			text,
			...options
		}, now, idOf());
		await this.domain.table("items").put(item.id, item);
		return item;
	}
	/** 勾选/取消（`update` 保证 CAS）。 */
	async toggle(id, now) {
		const table = this.domain.table("items");
		if (table.get(id) === void 0) return void 0;
		return table.update(id, (current) => toggle(current, now));
	}
	/** 改正文。 */
	async edit(id, text, now) {
		const table = this.domain.table("items");
		if (table.get(id) === void 0) return void 0;
		return table.update(id, (current) => edit(current, text, now));
	}
	/** 删除（物理删；已完成的历史由 `prune` 负责）。 */
	async remove(id) {
		return this.domain.table("items").delete(id);
	}
	/**
	* 清理（D-7）：已完成且超保留期的行。
	* 只在**打开域时**调用一次（避免每帧 I/O）。
	* @param now 当前时刻
	* @param retentionDays 保留天数（缺省 90）
	* @returns 清掉的条数
	*/
	async prune(now, retentionDays) {
		const table = this.domain.table("items");
		const ids = prunable(this.list(), now, retentionDays);
		let removed = 0;
		for (const id of ids) if (await table.delete(id)) removed += 1;
		return removed;
	}
	/** 最近一条简报（面板读）。 */
	latestDigest() {
		const table = this.domain.table("digests");
		let latest;
		for (const key of table.keys()) {
			const row = table.get(key);
			if (row === void 0) continue;
			if (latest === void 0 || row.createdAt > latest.createdAt) latest = row;
		}
		return latest;
	}
	/** 某天的简报。 */
	digestOf(date) {
		return this.domain.table("digests").get(date);
	}
	/** 写一条简报（同一天覆盖，幂等）。 */
	async saveDigest(digest) {
		await this.domain.table("digests").put(digest.id, digest);
		return digest;
	}
	/**
	* 清理超期简报。
	* @param now 当前时刻
	* @param retentionDays 保留天数（缺省 90）
	* @returns 清掉的条数
	*/
	async pruneDigests(now, retentionDays = 90) {
		const table = this.domain.table("digests");
		const cutoff = now - retentionDays * DAY_MS;
		let removed = 0;
		for (const key of table.keys()) {
			const row = table.get(key);
			if (row === void 0 || row.createdAt >= cutoff) continue;
			if (await table.delete(key)) removed += 1;
		}
		return removed;
	}
};
