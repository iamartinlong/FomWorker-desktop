/** 推送帧上限（与平台 `MaxReplyChars` 对齐，留一点余量）。 */
const MAX_PUSH_CHARS = 3800;
/**
* 把简报折成一条 IM 文本。
*
* 加一行抬头（日期 + 计数），让人在 IM 里不点开也知道是什么；
* 正文超长就截断——宁可少几行，也不让整条发不出去。
* @param digest 简报
* @returns 要发的正文
*/
function digestMessage(digest) {
	const head = `📋 ${digest.date} 日终收拢`;
	const stat = [
		digest.doneToday > 0 ? `完成 ${String(digest.doneToday)}` : null,
		digest.openCount > 0 ? `待办 ${String(digest.openCount)}` : "已清空",
		digest.overdueCount > 0 ? `逾期 ${String(digest.overdueCount)}` : null
	].filter((part) => part !== null).join(" · ");
	const full = `${head}\n${stat}\n\n${digest.text}`;
	if (full.length <= 3800) return full;
	const room = MAX_PUSH_CHARS - (head.length + stat.length + 2 + 2);
	return `${head}\n${stat}\n\n${[...digest.text].slice(0, Math.max(0, room)).join("")}…`;
}
/**
* 推一份简报（失败不抛）。
* @param digest 简报
* @param deps 通道
* @returns 是否真的发出去了
*/
function pushDigest(digest, deps) {
	if (deps.channel === void 0) return false;
	try {
		return deps.channel.send({
			type: "digest.notify",
			date: digest.date,
			text: digestMessage(digest)
		});
	} catch (error) {
		deps.warn?.(`简报推 IM 失败：${String(error?.message ?? error)}`);
		return false;
	}
}
