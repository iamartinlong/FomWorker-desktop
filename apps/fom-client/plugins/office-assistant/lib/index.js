/**
* 「从会话抄进来」的**编排**（纯逻辑 + 注入的 store），便于单测。
*
* 为什么要这样切：面板的 `main` 槽位拿不到 sessionId（框架只给 `{}` + `entryKey`），
* 所以取「**最近活跃会话**」的 `todos` 投影（内核 `todo_write` 的会话级清单）；
* 这一跳涉及会话/投影两个宿主服务 ⇒ 用**函数注入**把它们挡在测试之外。
*/
/** 把一批会话待办并入 store（按正文去重、只抄未完成）。 */
async function copyTodosIntoStore(store, todos, now, idOf, sessionId) {
	if (todos.length === 0) return [];
	const pending = copyFromSessionTodos(todos, store.list(), now, idOf);
	const created = [];
	for (const item of pending) created.push(await store.add(item.text, now, {
		source: "panel",
		...sessionId === void 0 ? {} : { sessionId }
	}));
	return created;
}
/** 本地日期键 `YYYY-MM-DD`。 */
function dateKeyOf(now) {
	const date = new Date(now);
	const month = String(date.getMonth() + 1).padStart(2, "0");
	const day = String(date.getDate()).padStart(2, "0");
	return `${String(date.getFullYear())}-${month}-${day}`;
}
/** 本地当天 00:00（UTC 毫秒）。 */
function startOfDay(now) {
	const date = new Date(now);
	date.setHours(0, 0, 0, 0);
	return date.getTime();
}
/** 下一次到点（本地 `hour:00`）的时刻；已过今天就顺延到明天。 */
function nextDigestAt(now, hour) {
	const clamped = Math.min(23, Math.max(0, Math.trunc(hour)));
	const target = new Date(now);
	target.setHours(clamped, 0, 0, 0);
	if (target.getTime() <= now) target.setDate(target.getDate() + 1);
	return target.getTime();
}
/** 简报该不该出：输入里**一条可说的都没有** ⇒ `undefined`。 */
function buildDigest(input) {
	const { items, now } = input;
	const todos = input.todos ?? [];
	const dayStart = startOfDay(now);
	const open = items.filter((item) => item.status === "open");
	const doneToday = items.filter((item) => item.status === "done" && (item.doneAt ?? item.updatedAt) >= dayStart);
	const overdue = open.filter((item) => isOverdue(item, now));
	const pendingTodos = todos.filter((todo) => todo.status === "pending" || todo.status === "in_progress");
	if (open.length === 0 && doneToday.length === 0 && pendingTodos.length === 0) return void 0;
	const lines = [];
	if (doneToday.length > 0) {
		const names = doneToday.slice(0, 3).map((item) => item.text).join("、");
		lines.push(`今天完成 ${doneToday.length} 条：${names}${doneToday.length > 3 ? " 等" : ""}`);
	}
	if (open.length === 0) lines.push("待办已清空");
	else {
		lines.push(overdue.length > 0 ? `还有 ${open.length} 条没做完，其中 ${overdue.length} 条已逾期` : `还有 ${open.length} 条没做完`);
		for (const item of open.slice(0, 12)) lines.push(`· ${isOverdue(item, now) ? "[逾期] " : ""}${item.text}`);
		if (open.length > 12) lines.push(`…还有 ${open.length - 12} 条`);
	}
	if (pendingTodos.length > 0) lines.push(`会话里还有 ${pendingTodos.length} 条未完成步骤`);
	const date = dateKeyOf(now);
	return {
		id: date,
		date,
		createdAt: now,
		openCount: open.length,
		doneToday: doneToday.length,
		overdueCount: overdue.length,
		lines,
		text: lines.join("\n")
	};
}
