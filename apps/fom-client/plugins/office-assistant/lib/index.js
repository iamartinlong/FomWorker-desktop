/**
* 出一份「今天」的简报并落盘。
*
* 空集不出版：`buildDigest` 给 `undefined` 时不写、也不返回。
* 读会话待办失败**不阻塞**简报（宁可少一行，也不要整份不出）。
* @param deps 取数与落盘
* @returns 写下的简报，或 `undefined`（今天没什么可收拢的）
*/
async function runDigest(deps) {
	let todos;
	if (deps.readTodos !== void 0) try {
		todos = await deps.readTodos();
	} catch (error) {
		process.stderr.write(`[office-assistant] 简报读会话失败（忽略）：${String(error?.message ?? error)}\n`);
		todos = void 0;
	}
	const now = deps.now();
	const digest = buildDigest({
		items: deps.listItems(),
		now,
		...todos === void 0 ? {} : { todos }
	});
	if (digest === void 0) return void 0;
	return deps.save(digest);
}
