/** 定时器上限（`setTimeout` 单次不能超过 24.8 天，这里按 1 小时一轮更稳）。 */
const DIGEST_POLL_MS = 36e5;
/**
* 日终定时：等到下一个 `hour:00`（分片睡，单片不超过 1 小时）。
*
* 为什么用分片而不是一次长定时：机器休眠/关机后长 `setTimeout` 会漂；
* 分片每次重新算「离下个整点还有多久」，睡醒后自然补上。
* 同一天重复出也无害（简报按日期覆盖，幂等）。
* @param ctx 宿主上下文（取 `effect` 以便随插件卸载）
* @param hour 出简报的本地小时（0–23）
* @param generate 出简报（内部已做「空集不出版」）
* @param hasToday 今天那份是否已经出过
*/
function scheduleDailyDigest(ctx, hour, generate, hasToday) {
	let stopped = false;
	let timer;
	const arm = () => {
		if (stopped) return;
		const now = Date.now();
		const target = nextDigestAt(now, hour);
		const remaining = Math.max(1e3, target - now);
		const chunk = Math.min(remaining, DIGEST_POLL_MS);
		const isFinal = chunk >= remaining;
		timer = setTimeout(() => {
			if (stopped) return;
			if (isFinal && !hasToday()) generate().catch((error) => {
				process.stderr.write(`[office-assistant] 日终简报失败：${String(error?.message ?? error)}\n`);
			});
			arm();
		}, chunk);
		timer.unref?.();
	};
	ctx.effect(() => {
		arm();
		return () => {
			stopped = true;
			if (timer !== void 0) clearTimeout(timer);
		};
	}, "office-assistant: 日终收拢定时");
}
function json(body, status) {
	return new Response(JSON.stringify(body), {
		status,
		headers: { "content-type": "application/json" }
	});
}
const createInput = object({
	text: string(),
	dueAt: number().int().nonnegative().optional(),
	/** 「从会话抄进来」用。 */
	sessionId: string().max(100).optional()
});
const editInput = object({ text: string() });
/**
* 「最近活跃会话」的 todos 投影（「抄进来」的来源）。
*
* 面板的 `main` 槽位拿不到 sessionId（框架只给 `{}` + `entryKey`），所以取**最近活跃**的那个会话；
* 两者都读不到（没开会话 / 该会话还没有 `todo_write`）⇒ `undefined`，由调用方回一句人话。
* @param ctx 宿主上下文（需 `sessions` + `sessionProjections`）
*/
async function readRecentTodos(ctx) {
	const declared = ctx;
	const sessions = declared.sessions ?? ctx.get("sessions");
	if (sessions?.list === void 0) return void 0;
	const latest = [...sessions.list()].filter((row) => typeof row.id === "string").sort((left, right) => Number(right.createdAt ?? 0) - Number(left.createdAt ?? 0))[0];
	if (latest?.id === void 0) return void 0;
	const sessionId = String(latest.id);
	const projections = declared.sessionProjections ?? ctx.get("sessionProjections");
	if (projections === void 0) return void 0;
	const session = sessions.get?.(sessionId);
	if (session === void 0) return void 0;
	let todos;
	if (projections.snapshot !== void 0) todos = projections.snapshot(session).values?.todos;
	else if (projections.read !== void 0) todos = projections.read("todos", session);
	if (!Array.isArray(todos)) return void 0;
	const normalized = todos.filter((item) => item !== null && typeof item === "object" && typeof item.content === "string" && typeof item.status === "string").map((item) => ({
		content: item.content,
		status: item.status
	}));
	return normalized.length === 0 ? void 0 : {
		sessionId,
		todos: normalized
	};
}
/**
* 造「日常事项」路由处理器（与接线拆开，便于单测）。
* @param store 域上的薄壳
* @param now 时钟（UTC 毫秒，注入便于测试）
* @param copySource 「从最近活跃会话抄进来」的来源（宿主读会话 + todos 投影；缺省不可用）
*/
function createItemsFetch(store, now = Date.now, copySource = async () => void 0, generateDigest = async () => void 0) {
	return async (request) => {
		const method = request.method.toUpperCase();
		const url = new URL(request.url);
		const id = url.searchParams.get("id") ?? "";
		const action = url.searchParams.get("action") ?? "";
		try {
			if (method === "GET") {
				if (action === "digest") return json({
					ok: true,
					digest: store.latestDigest() ?? null
				}, 200);
				return json({
					ok: true,
					items: store.list(),
					digest: store.latestDigest() ?? null
				}, 200);
			}
			if (method === "POST") {
				if (action === "digest") {
					const digest = await generateDigest();
					return digest === void 0 ? json({
						ok: true,
						digest: null,
						message: "今天没有可收拢的事"
					}, 200) : json({
						ok: true,
						digest
					}, 200);
				}
				if (action === "copy-session") {
					const source = await copySource();
					if (source === void 0) return json({
						ok: false,
						message: "没找到可抄的会话（先开一个会话聊聊）"
					}, 200);
					return json({
						ok: true,
						created: (await copyTodosIntoStore(store, source.todos, now(), () => crypto.randomUUID(), source.sessionId)).length,
						sessionId: source.sessionId
					}, 200);
				}
				const parsed = createInput.safeParse(await request.json().catch(() => void 0));
				if (!parsed.success) return json({
					ok: false,
					message: "参数不对：需要 { text }"
				}, 400);
				return json({
					ok: true,
					item: await store.add(parsed.data.text, now(), {
						...parsed.data.dueAt === void 0 ? {} : { dueAt: parsed.data.dueAt },
						...parsed.data.sessionId === void 0 ? {} : { sessionId: parsed.data.sessionId }
					})
				}, 200);
			}
			if (method === "PATCH") {
				if (id === "") return json({
					ok: false,
					message: "缺少 id"
				}, 400);
				const parsed = editInput.safeParse(await request.json().catch(() => void 0));
				if (!parsed.success) return json({
					ok: false,
					message: "参数不对：需要 { text }"
				}, 400);
				const item = await store.edit(id, parsed.data.text, now());
				return item === void 0 ? json({
					ok: false,
					message: "事项不存在"
				}, 404) : json({
					ok: true,
					item
				}, 200);
			}
			if (method === "DELETE") {
				if (id === "") return json({
					ok: false,
					message: "缺少 id"
				}, 400);
				return await store.remove(id) ? json({ ok: true }, 200) : json({
					ok: false,
					message: "事项不存在"
				}, 404);
			}
			if (method === "PUT" && url.searchParams.get("action") === "toggle") {
				if (id === "") return json({
					ok: false,
					message: "缺少 id"
				}, 400);
				const item = await store.toggle(id, now());
				return item === void 0 ? json({
					ok: false,
					message: "事项不存在"
				}, 404) : json({
					ok: true,
					item
				}, 200);
			}
			return json({
				ok: false,
				message: `不支持的请求：${method} ${url.pathname}`
			}, 405);
		} catch (error) {
			return json({
				ok: false,
				message: String(error?.message ?? error)
			}, 400);
		}
	};
}
/**
* 挂路由 + 打开域。
* @param ctx 宿主上下文
* @param config 平台地址
*/
function apply(ctx, config = {}) {
	const platformUrl = (config.platformUrl ?? DEFAULT_PLATFORM_URL).replace(/\/+$/u, "");
	const digestHour = config.digestHour ?? DEFAULT_DIGEST_HOUR;
	const facility = ctx.storageDomain ?? ctx.get("storageDomain");
	if (facility !== void 0) facility.open(assistantItemsDomain).then(async (domain) => {
		const store = new ItemStore(domain);
		const pruned = await store.prune(Date.now());
		if (pruned > 0) process.stderr.write(`[office-assistant] 已清理 ${pruned} 条超期已完成事项\n`);
		store.pruneDigests(Date.now());
		const generateDigest = async () => {
			const digest = await runDigest({
				listItems: () => store.list(),
				readTodos: async () => (await readRecentTodos(ctx))?.todos,
				save: (saved) => store.saveDigest(saved),
				now: Date.now
			});
			if (digest !== void 0 && (config.digestPush ?? true)) pushDigest(digest, {
				channel: ctx.get("officeImChannel"),
				warn: (message) => process.stderr.write(`[office-assistant] ${message}\n`)
			});
			return digest;
		};
		if (digestHour >= 0) scheduleDailyDigest(ctx, digestHour, generateDigest, () => store.digestOf(dateKeyOf(Date.now())) !== void 0);
		ctx.inject(["connection"], (connCtx) => {
			connCtx.effect(() => {
				const conn = connCtx.get("connection");
				if (conn === void 0) return () => {};
				const dispose = conn.fetch.register({
					path: ITEMS_ROUTE,
					methods: [
						"GET",
						"POST",
						"PATCH",
						"PUT",
						"DELETE"
					],
					requestBody: "buffered",
					fetch: (request) => createItemsFetch(store, Date.now, () => readRecentTodos(ctx), generateDigest)(request)
				});
				return () => {
					dispose();
				};
			}, "office-assistant: 日常事项（读/增/勾/改/删 + 日终简报）");
		});
	}).catch((error) => {
		process.stderr.write(`[office-assistant] 日常事项域打开失败：${String(error?.message ?? error)}\n`);
	});
	ctx.inject(["connection"], (connCtx) => {
		connCtx.effect(() => {
			const conn = connCtx.get("connection");
			if (conn === void 0) return () => {};
			const dispose = conn.fetch.register({
				path: TASKS_ROUTE,
				methods: ["GET", "POST"],
				requestBody: "buffered",
				fetch: (request) => {
					const creds = connCtx.get("credentials");
					if (creds === void 0) return Promise.resolve(json({
						ok: false,
						message: "凭据服务不可用（credentials）"
					}, 500));
					return createTasksFetch({
						platformUrl,
						credentials: creds
					})(request);
				}
			});
			return () => {
				dispose();
			};
		}, "office-assistant: 我的任务 / 派活（宿主代理平台）");
	});
}
