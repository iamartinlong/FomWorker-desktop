/**
* `office-assistant` 的 host 半：把「我的任务 / 派活」代理到平台（**令牌不过浏览器**）。
*
* 为什么需要代理：浏览器不直连平台（平台不开 CORS）；宿主用凭据库里的
* `FOM_PLATFORM_TOKEN` 去打平台 `/api/tasks`，只把结果回给面板。
*/
/** 面板用的代理路由。 */
const TASKS_ROUTE = "/api/office/tasks";
/** 平台令牌的凭据 ref（与 office-login 一致）。 */
const PLATFORM_TOKEN_REF = "FOM_PLATFORM_TOKEN";
function json$1(body, status) {
	return new Response(JSON.stringify(body), {
		status,
		headers: { "content-type": "application/json" }
	});
}
async function token(deps) {
	return (await deps.credentials.resolve?.("FOM_PLATFORM_TOKEN"))?.value ?? "";
}
/**
* 造「我的任务」代理：
* - `GET` ⇒ 平台 `/api/tasks` ⇒ `{ ok, tasks }`；
* - `POST { text }` ⇒ 平台 `/api/tasks`（派活，桌面不在线回 503）⇒ `{ ok, status, taskId? }`。
* @param deps 平台地址 / 凭据 / fetch。
*/
function createTasksFetch(deps) {
	const doFetch = deps.fetchImpl ?? fetch;
	return async (request) => {
		const accessToken = await token(deps);
		if (accessToken === "") return json$1({
			ok: false,
			message: "未登录（先在账号面板登录）"
		}, 401);
		const auth = { authorization: `Bearer ${accessToken}` };
		const method = request.method.toUpperCase();
		if (method === "GET") {
			let res;
			try {
				res = await doFetch(`${deps.platformUrl}/api/tasks`, { headers: auth });
			} catch (error) {
				return json$1({
					ok: false,
					message: `连不上平台（${deps.platformUrl}）：${String(error?.message ?? error)}`
				}, 200);
			}
			if (!res.ok) return json$1({
				ok: false,
				status: res.status,
				message: await res.text().catch(() => "")
			}, 200);
			const tasks = await res.json().catch(() => []);
			return json$1({
				ok: true,
				tasks: Array.isArray(tasks) ? tasks : []
			}, 200);
		}
		if (method === "POST") {
			let body;
			try {
				body = await request.json();
			} catch {
				return json$1({
					ok: false,
					message: "请求体不是 JSON"
				}, 400);
			}
			const text = typeof body.text === "string" ? body.text.trim() : "";
			if (text === "") return json$1({
				ok: false,
				message: "说点什么再派活"
			}, 400);
			if (text.length > 4e3) return json$1({
				ok: false,
				message: "正文最长 4000 字"
			}, 400);
			let res;
			try {
				res = await doFetch(`${deps.platformUrl}/api/tasks`, {
					method: "POST",
					headers: {
						...auth,
						"content-type": "application/json"
					},
					body: JSON.stringify({ text })
				});
			} catch (error) {
				return json$1({
					ok: false,
					message: `连不上平台（${deps.platformUrl}）：${String(error?.message ?? error)}`
				}, 200);
			}
			const payload = await res.json().catch(() => ({}));
			if (!res.ok) {
				const reason = res.status === 503 ? "桌面不在线——先打开 FomWorker 再派活" : `平台回 ${res.status}`;
				return json$1({
					ok: false,
					status: res.status,
					message: reason
				}, 200);
			}
			return json$1({
				ok: true,
				taskId: typeof payload.taskId === "string" ? payload.taskId : ""
			}, 200);
		}
		return json$1({
			ok: false,
			message: `不支持的请求方法 ${method}`
		}, 405);
	};
}
