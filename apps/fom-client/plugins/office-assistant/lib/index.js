/** 校验正文：空/超长 ⇒ 错误文案；合法 ⇒ `undefined`。 */
function textError(text) {
	const normalized = normalizeText(text);
	if (normalized === "") return "写点什么";
	if ([...normalized].length > 500) return `最多 500 字`;
}
/**
* 造一条新事项。
* @param input 正文 / 来源 / 可选到期与会话
* @param now 当前时刻（UTC 毫秒，注入便于测试）
* @param id 可注入 id（缺省由调用方给）
* @returns 新行（未持久化）
*/
function newItem(input, now, id) {
	const text = normalizeText(input.text);
	const error = textError(text);
	if (error !== void 0) throw new Error(error);
	return {
		id,
		text,
		status: "open",
		createdAt: now,
		updatedAt: now,
		source: input.source ?? "panel",
		...input.dueAt === void 0 ? {} : { dueAt: input.dueAt },
		...input.sessionId === void 0 ? {} : { sessionId: input.sessionId }
	};
}
/** 勾选/取消勾选（写 `doneAt` 与 `updatedAt`）。 */
function toggle(item, now) {
	if (item.status === "open") return {
		...item,
		status: "done",
		doneAt: now,
		updatedAt: now
	};
	const { doneAt: _doneAt, ...rest } = {
		...item,
		status: "open",
		updatedAt: now
	};
	return rest;
}
/** 改正文（trim + 校验）。 */
function edit(item, text, now) {
	const normalized = normalizeText(text);
	const error = textError(normalized);
	if (error !== void 0) throw new Error(error);
	return {
		...item,
		text: normalized,
		updatedAt: now
	};
}
/** 排序（D-6）：未完成在前；有到期按到期升序；同档按更新时间降序。 */
function sortItems(items) {
	const rank = (item) => item.status === "open" ? 0 : 1;
	return [...items].sort((left, right) => {
		if (rank(left) !== rank(right)) return rank(left) - rank(right);
		if (left.status === "open") {
			const leftDue = left.dueAt ?? Number.POSITIVE_INFINITY;
			const rightDue = right.dueAt ?? Number.POSITIVE_INFINITY;
			if (leftDue !== rightDue) return leftDue - rightDue;
		}
		return right.updatedAt - left.updatedAt;
	});
}
/** 该清掉哪些（D-7）：已完成且 `doneAt` 早于保留期。返回 id 列表（不改入参）。 */
function prunable(items, now, retentionDays = 90) {
	const cutoff = now - retentionDays * DAY_MS$1;
	return items.filter((item) => item.status === "done" && (item.doneAt ?? item.updatedAt) < cutoff).map((item) => item.id);
}
/** 到期标记（v1 只用于显示）：未完成且 `dueAt <= now`。 */
function isOverdue(item, now) {
	return item.status === "open" && item.dueAt !== void 0 && item.dueAt <= now;
}
/**
* 「从当前会话的 todo 抄进来」（D-9）：只抄未完成的、按「正文 + 未完成」去重。
* @param todos 会话投影里的待办（`content` + `status`，内核 `todo_write` 的形状）
* @param existing 已有事项
* @param now 当前时刻
* @param idOf 造 id（注入便于测试）
* @returns 需要新建的行（已存在的跳过）
*/
function copyFromSessionTodos(todos, existing, now, idOf) {
	const seen = new Set(existing.filter((item) => item.status === "open").map((item) => normalizeText(item.text)));
	const created = [];
	for (const todo of todos) {
		if (todo.status !== "pending" && todo.status !== "in_progress") continue;
		const text = normalizeText(todo.content);
		if (text === "" || seen.has(text)) continue;
		seen.add(text);
		created.push(newItem({
			text,
			source: "panel"
		}, now, idOf()));
	}
	return created;
}
